  await writeFile(join(fixture, "package.json"), JSON.stringify(manifest));
  await writeFile(join(fixture, "package-lock.json"), JSON.stringify({ name: manifest.name, version: manifest.version, lockfileVersion: 3, packages: { "": { name: manifest.name, version: manifest.version, hasInstallScript: true } } }));

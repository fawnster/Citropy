test("SSH configuration rejects command injection and persists only connection details", async t => {
  const directory = await mkdtemp(join(tmpdir(), "citropy-ssh-config-"));
  t.after(() => rm(directory, { recursive: true, force: true }));
  for (const target of ["-oProxyCommand=touch /tmp/no", "host;pwd", "a@host\nwhoami", "a@$(pwd)", "a@host/path"])
    assert.throws(() => validateConnection({ name: "Test", target }));
  for (const port of [0.5, -1, 65536, "bad"]) assert.throws(() => validateConnection({ name: "Test", target: "host", port }));
  assert.throws(() => validateConnection({ name: "Test", target: "host", node: "node --eval code" }));
  assert.equal(validateConnection({ name: "Test", target: "user@[::1]" }).target, "user@[::1]");
  assert.ok(sshArguments({ port: 22 }).includes("StrictHostKeyChecking=yes"));
  assert.ok(!sshArguments({ port: 0 }).includes("-p"));
  assert.deepEqual(sshArguments({ port: 22 }).slice(-2), ["-p", "22"]);
  assert.deepEqual(sshArguments({ port: 2200 }).slice(-2), ["-p", "2200"]);
  const text = "a 'quoted' $(command) `command`\nfile";
  assert.equal((await run("sh", ["-c", `printf %s ${shellQuote(text)}`])).stdout, text);
  const config = join(directory, "config");
  await writeFile(config, "Host one two\n HostName private\nHost * !no prod-*\nHost one\n");
  assert.deepEqual(await sshHosts(config), ["one", "two"]);
  const manager = new SshEnvironments({ directory, appRoot: root, origin: "http://127.0.0.1:4177" });
  await manager.load();
  const saved = await manager.save({ name: "Development", target: "host", port: 22 });
  await assert.rejects(manager.save({ name: "Duplicate", target: "host", port: 22 }), /already saved/);
  const another = new SshEnvironments({ directory, appRoot: root, origin: manager.origin });
  await another.load();
  assert.deepEqual(another.connections, [saved]);
  assert.equal((await stat(join(directory, "ssh.json"))).mode & 0o777, 0o600);
  assert.ok(!JSON.stringify(another.state()).includes("token"));
  await another.remove(saved.id);
  assert.deepEqual(another.state().connections, []);
});

test("the remote proxy authenticates HTTP and WebSocket requests and never falls back locally", async t => {
  const token = "secret".repeat(12);
  const pending = Promise.withResolvers();
  const server = createServer((req, res) => {
    assert.equal(req.headers["x-citropy-remote-token"], token);
    assert.equal(req.headers.origin, `http://127.0.0.1:${port}`);
    assert.equal(req.headers.cookie, undefined);
    if (req.url === "/api/slow") { pending.resolve(res); return; }
    res.writeHead(200, { "content-type": "application/json" }).end(JSON.stringify({ remote: true, method: req.method }));
  });
  const port = await listen(server);
  const wss = new WebSocketServer({ server, verifyClient: ({ req }) => req.headers["x-citropy-remote-token"] === token });
  wss.on("connection", socket => socket.on("message", data => socket.send(data)));
  const origin = "http://127.0.0.1:4177";
  const proxy = await remoteProxy(origin);
  t.after(async () => {
    await proxy.close();
    for (const client of wss.clients) client.terminate();
    wss.close();
    server.closeAllConnections();
    server.close();
  });
  proxy.setTarget({ port, remotePort: port, token });
  const response = await fetch(`${proxy.endpoint}/api/example`, { headers: { origin, cookie: "local-secret=true" } });
  assert.equal(response.headers.get("access-control-allow-origin"), origin);
  assert.deepEqual(await response.json(), { remote: true, method: "GET" });
  assert.equal((await fetch(`${proxy.endpoint}/api/example`, { method: "OPTIONS", headers: { origin, "access-control-request-method": "PATCH" } })).status, 204);
  assert.equal((await fetch(`${proxy.endpoint}/api/example`, { headers: { origin: "https://evil.invalid" } })).status, 403);
  assert.equal(await new Promise(resolve => { const req = request(`${proxy.endpoint}/api/example`, { headers: { host: "evil.invalid" } }, response => { response.resume(); resolve(response.statusCode); }); req.end(); }), 403);
  assert.equal((await fetch(`${proxy.endpoint}/api/example`, { headers: { origin, "sec-fetch-site": "cross-site" } })).status, 200);
  assert.equal((await fetch(`${proxy.endpoint}/api/example`, { headers: { "sec-fetch-site": "cross-site", referer: "https://evil.invalid" } })).status, 403);
  assert.equal((await fetch(`${proxy.endpoint}/api/example`, { headers: { "sec-fetch-site": "cross-site", referer: origin } })).status, 200);
  assert.equal((await fetch(`${proxy.endpoint}/api/remote/shutdown`, { method: "POST", headers: { origin } })).status, 404);
  assert.equal((await fetch(`${proxy.endpoint}/mcp/task`, { headers: { origin } })).status, 404);
  const socket = new WebSocket(proxy.endpoint.replace("http", "ws") + "/socket", { origin });
  await once(socket, "open");
  socket.send("remote output");
  assert.equal(String((await once(socket, "message"))[0]), "remote output");
  const closed = once(socket, "close");
  proxy.setTarget(undefined);
  await closed;
  assert.equal((await fetch(`${proxy.endpoint}/api/example`, { headers: { origin } })).status, 503);
  proxy.setTarget({ port, remotePort: port, token });
  assert.equal((await fetch(`${proxy.endpoint}/api/example`, { headers: { origin } })).status, 200);
  for (let attempt = 0; attempt < 20; attempt++) {
    const connected = await fetch(`${proxy.endpoint}/api/example`, { headers: { origin } });
    await connected.json();
    proxy.setTarget(undefined);
    const disconnected = await fetch(`${proxy.endpoint}/api/example`, { headers: { origin } });
    assert.equal(disconnected.status, 503);
    await disconnected.json();
    proxy.setTarget({ port, remotePort: port, token });
  }
  const slow = fetch(`${proxy.endpoint}/api/slow`, { headers: { origin } });
  const delayed = await pending.promise;
  proxy.setTarget(undefined);
  const cancelled = await slow;
  assert.equal(cancelled.status, 503);
  assert.match((await cancelled.json()).error, /connection changed/);
  delayed.end("old host response");
  proxy.setTarget({ port, remotePort: port, token });
  assert.equal((await fetch(`${proxy.endpoint}/api/example`, { headers: { origin } })).status, 200);
});

